/**
 * Writes src/lib/route-slugs.ts from defaults + optional data/orbit-content.json (build/deploy).
 */
import { readFileSync, writeFileSync, existsSync } from "fs";
import path from "path";

const root = process.cwd();
const orbitPath = path.join(root, "data", "orbit-content.json");

function readOrbit() {
  if (!existsSync(orbitPath)) return null;
  try {
    return JSON.parse(readFileSync(orbitPath, "utf8"));
  } catch {
    return null;
  }
}

function slugsFromDefaultServices() {
  const file = path.join(root, "src", "lib", "default-services.ts");
  const src = readFileSync(file, "utf8");
  const slugs = [];
  const re = /menuService\(\s*\n\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(src))) slugs.push(m[1]);
  return slugs;
}

function slugsFromContentPackages() {
  const file = path.join(root, "src", "lib", "content.ts");
  const src = readFileSync(file, "utf8");
  const slugs = [];
  const re = /slug:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(src))) slugs.push(m[1]);
  return slugs;
}

const defaultServiceSlugs = slugsFromDefaultServices();
const defaultPackageSlugs = slugsFromContentPackages();

const orbit = readOrbit();
const serviceSlugs = new Set(defaultServiceSlugs);
const packageSlugs = new Set(defaultPackageSlugs);
if (orbit?.services) {
  for (const s of orbit.services) {
    if (s?.slug) serviceSlugs.add(s.slug);
  }
}
if (orbit?.packages) {
  for (const p of orbit.packages) {
    if (p?.slug) packageSlugs.add(p.slug);
  }
}

const out = `/** Generated by scripts/write-route-slug-manifest.mjs — do not edit manually */\nexport const knownServiceSlugs = new Set(${JSON.stringify([...serviceSlugs].sort(), null, 2)});\nexport const knownPackageSlugs = new Set(${JSON.stringify([...packageSlugs].sort(), null, 2)});\n`;

writeFileSync(path.join(root, "src", "lib", "route-slugs.ts"), out, "utf8");
console.log(
  "write-route-slug-manifest:",
  serviceSlugs.size,
  "services,",
  packageSlugs.size,
  "packages",
);
